"""
Risk of ruin under my actual bankroll rule, not the fixed-stake textbook case.

    python -m src.move_down

The rule
--------
- Play a stake only with at least 50 buy-ins for it (1 buy-in = 100 bb).
- Move down one stake when the bankroll falls below 30 buy-ins of the current stake.
- Move back up once the bankroll is again worth 50 buy-ins of the stake above,
  but never above the starting stake (this study is about survival, not growth).

The fixed-stake formula in bankroll.py assumes you never move down, so it
measures the chance of losing all 50 buy-ins at one stake. Moving down shrinks
the bet as the bankroll shrinks, the same reason a Kelly bettor survives.

Modelling choices (see the README for limitations)
- Stakes form a ladder with a ratio of 2 (for example NL200, NL100, NL50).
- The ladder has `levels_below` stakes under the starting one. "Ruin" here means
  the rule is exhausted: the bankroll falls below 30 buy-ins of the LOWEST stake,
  so there is nowhere left to move down to.
- The win rate and SD in bb/100 are the same at every stake. In reality win
  rates tend to be higher at lower stakes, so this is a conservative choice.
- Each 100-hand block uses the same random draws as the fixed-stake simulation,
  so both rules face exactly the same luck.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from . import winrate
from .bankroll import BB_PER_BUYIN
from .simulate import BLOCK, simulate_blocks

ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = ROOT / "results"


def run_rule(blocks: np.ndarray, start_buyins: float = 50, move_down_below: float = 30,
             move_up_at: float = 50, levels_below: int = 2, stake_ratio: float = 2.0) -> dict:
    """
    Apply the move-down rule to pre-drawn block results.

    `blocks` has shape (n_careers, n_blocks); each entry is the result of 100
    hands in big blinds OF THE STAKE BEING PLAYED. The bankroll is tracked in
    big blinds of the STARTING stake.
    """
    n, n_blocks = blocks.shape
    bb = BB_PER_BUYIN
    bankroll = np.full(n, start_buyins * bb, dtype=float)
    level = np.zeros(n, dtype=int)            # 0 = starting stake, 1 = one stake down, ...
    ruined = np.zeros(n, dtype=bool)
    ever_down = np.zeros(n, dtype=bool)
    blocks_below = np.zeros(n, dtype=int)
    floor = move_down_below * bb * stake_ratio ** -levels_below   # 30 buy-ins of the lowest stake

    for t in range(n_blocks):
        active = ~ruined
        size = stake_ratio ** -level.astype(float)
        bankroll = np.where(active, bankroll + blocks[:, t] * size, bankroll)

        # Move down (possibly more than one stake after a very bad block).
        for _ in range(levels_below):
            size = stake_ratio ** -level.astype(float)
            down = active & (level < levels_below) & (bankroll < move_down_below * bb * size)
            if not down.any():
                break
            level = level + down

        ruined |= active & (level == levels_below) & (bankroll < floor)

        # Move up one stake when the bankroll covers 50 buy-ins of the stake above.
        up_size = stake_ratio ** -(level - 1).astype(float)
        up = ~ruined & (level > 0) & (bankroll >= move_up_at * bb * up_size)
        level = level - up

        ever_down |= level > 0
        blocks_below += (~ruined) & (level > 0)

    return {"ruined": ruined, "ever_down": ever_down, "blocks_below": blocks_below,
            "final_bankroll_bb": bankroll}


def compare(wr: float, sd: float, hands: int = 500_000, n_careers: int = 4000,
            seed: int = 11, **rule) -> dict:
    """Same luck, two rules: fixed stake (lose 50 buy-ins = ruin) vs. the move-down rule."""
    blocks = simulate_blocks(wr, sd, hands, n_careers, seed=seed)
    paths = np.cumsum(blocks, axis=1)
    start = rule.get("start_buyins", 50)
    fixed_ruin = float((paths.min(axis=1) <= -start * BB_PER_BUYIN).mean())
    r = run_rule(blocks, **rule)
    n_blocks = blocks.shape[1]
    return {"wr": wr, "sd": sd, "fixed_ruin": fixed_ruin,
            "rule_ruin": float(r["ruined"].mean()),
            "ever_down": float(r["ever_down"].mean()),
            "median_share_below": float(np.median(r["blocks_below"] / n_blocks)),
            "hands": hands, "n_careers": n_careers}


def main() -> None:
    RESULTS_DIR.mkdir(exist_ok=True)
    hands = 500_000
    rows = []
    for sd in (70, 100, 130):
        low = winrate.confidence_interval(4.0, sd, hands)[0]
        for wr in (4.0, round(low, 2)):
            rows.append(compare(wr, sd, hands))
            print(rows[-1])

    L = ["# Move-down rule vs. fixed stake (generated by src/move_down.py)", "",
         "Rule: at least 50 buy-ins per stake, move down one stake below 30 buy-ins, "
         "move back up at 50 buy-ins of the stake above (never above the starting stake). "
         "1 buy-in = 100 bb. Stake ladder ratio 2, two stakes below the starting one. "
         "'Ruin' under the rule = below 30 buy-ins of the lowest stake.", "",
         f"{rows[0]['n_careers']:,} simulated careers of {hands:,} hands each; "
         "both rules use the same random draws.", "",
         "| SD (bb/100) | True win rate (bb/100) | Fixed stake: lose all 50 buy-ins | "
         "Move-down rule: ruin | Careers that ever moved down | Median share of hands below the starting stake |",
         "|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['sd']} | {r['wr']:.2f} | {r['fixed_ruin']:.1%} | {r['rule_ruin']:.2%} | "
                 f"{r['ever_down']:.0%} | {r['median_share_below']:.0%} |")
    L += ["", "## How much depends on the number of stakes below (SD 100)", "",
          "| Stakes below the starting one | True win rate (bb/100) | Move-down rule: ruin |",
          "|---|---|---|"]
    low100 = round(winrate.confidence_interval(4.0, 100, hands)[0], 2)
    for levels in (1, 2, 3):
        for wr in (4.0, low100):
            r = compare(wr, 100, hands, levels_below=levels)
            L.append(f"| {levels} | {wr:.2f} | {r['rule_ruin']:.2%} |")

    out = RESULTS_DIR / "move_down_summary.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
